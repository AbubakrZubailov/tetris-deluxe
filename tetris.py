    def go(self, state):
        self.held.clear()
        self.state = state
        self.sound.play('select', self.settings)

    def start(self, mode=None):
        if self.game and not self.game._recorded and not self.game.over:
            self.game.finish('Restarted')
            self.store.record_game(self.game)
        self.last_mode = mode or self.last_mode
        self.game = Game(self.last_mode)
        self.latest_awards = []
        self.game.take_events()
        self.held.clear()
        self.gravity_elapsed = 0.
        self.clear_elapsed = 0.
        self.particles = []
        self.flash = 0.
        self.state = 'playing'
        self.sound.play('select', self.settings)

    def abandon(self):
        if self.game and not self.game.over and not self.game._recorded:
            self.game.finish('Left game')
            self.store.record_game(self.game)
        self.go('menu')

    def show_result(self):
        if not self.game:
            self.go('menu')
            return
        if not self.game._recorded:
            self.latest_awards = self.store.record_game(self.game)
        self.held.clear()
        self.state = 'result'

    def draw_block(self, x, y, sz, color, ghost=False, alpha=255):
        p = self.palette
        rect = pygame.Rect(int(x), int(y), max(1, int(sz-1)), max(1, int(sz-1)))
        if ghost:
            pygame.draw.rect(self.canvas, blend(p['panel'], color, .63), rect, 2, border_radius=4)
            return
        base = color if self.settings['theme'] != 'Minimal' else blend(color, (209, 217, 215), .45)
        if alpha < 255:
            transparent = pygame.Surface((rect.w, rect.h), pygame.SRCALPHA)
            pygame.draw.rect(transparent, (*base, alpha), transparent.get_rect(), border_radius=4)
            pygame.draw.rect(transparent, (*blend(base, (255, 255, 255), .4), int(alpha * .72)),
                             (2, 2, rect.w-4, 4), border_radius=2)
            self.canvas.blit(transparent, rect.topleft)
            return
        if self.settings['effects'] and self.settings['theme'] == 'Neon':
            pygame.draw.rect(self.canvas, blend(p['panel'], color, .38), rect.inflate(3, 3), 1, border_radius=5)
        pygame.draw.rect(self.canvas, base, rect, border_radius=4)
        pygame.draw.rect(self.canvas, blend(base, (255, 255, 255), .5),
                         (rect.x+3, rect.y+3, rect.w-6, max(2, rect.h//6)), border_radius=3)
        pygame.draw.rect(self.canvas, blend(base, p['bg'], .42), rect, 1, border_radius=4)

    def emit(self, count, x, y, color, wide=70):
        if not self.settings['effects']:
            return
        for _ in range(count):
            angle = random.uniform(0, math.pi*2)
            speed = random.uniform(65, 255)
            self.particles.append(Particle(x+random.uniform(-wide, wide), y,
                                           math.cos(angle)*speed, math.sin(angle)*speed - 55,
                                           random.uniform(.27, .78), .78, random.uniform(1.8, 4.6), color))
        self.particles = self.particles[-250:]

    def update_particles(self, dt):
        if not self.settings['effects']:
            self.particles.clear()
            self.flash = 0.
            return
        alive = []
        for dot in self.particles:
            dot.x += dot.vx * dt
            dot.y += dot.vy * dt
            dot.vy += 255 * dt
            dot.life -= dt
            if dot.life > 0:
                alive.append(dot)
        self.particles = alive
        self.flash = max(0, self.flash - dt * 3.2)

    def draw_particles(self):
        for dot in self.particles:
            color = blend(self.palette['bg'], dot.color, max(0., min(1., dot.life/dot.maximum)))
            pygame.draw.circle(self.canvas, color, (int(dot.x), int(dot.y)), max(1, int(dot.radius)))

    def consume_events(self):
        if not self.game:
            return
        for name, detail in self.game.take_events():
            if name == 'clear_start':
                self.clear_elapsed = 0.
            if name in ('move', 'rotate', 'drop', 'lock', 'level', 'finish'):
                self.sound.play(name, self.settings)
            if name == 'clear':
                self.sound.play('clear', self.settings)
                self.flash = max(self.flash, .13)
                self.emit(18 * detail['count'], BX+BW//2, BY+BH//2, self.palette['primary'], 130)
            if name == 'tetris':
                self.sound.play('tetris', self.settings)
                self.flash = 1.
                self.emit(105, BX+BW//2, BY+BH//2, self.palette['second'], 140)
            if name == 'finish':
                self.show_result()

    def update_game(self, dt):
        if self.state != 'playing' or not self.game:
            return
        self.game.tick(dt)
        self.consume_events()
        if self.state != 'playing':
            return
        if self.game.pending_rows:
            self.clear_elapsed += dt
            if self.clear_elapsed >= ANIMATION_DURATION:
                self.game.resolve_clear()
                self.clear_elapsed = 0.
                self.consume_events()
            return
        for action in ('left', 'right', 'soft_drop'):
            if action in self.held:
                self.held[action] += dt
                initial = .19 if action != 'soft_drop' else .08
                period = .072 if action != 'soft_drop' else .032
                if self.held[action] >= initial:
                    self.repeat_elapsed[action] = self.repeat_elapsed.get(action, 0) + dt
                    if self.repeat_elapsed[action] >= period:
                        self.repeat_elapsed[action] -= period
                        self.action(action)
        self.gravity_elapsed += dt
        interval = gravity_interval(self.game.level, self.settings['difficulty'], self.settings['speed'])
        if self.gravity_elapsed >= interval:
            self.gravity_elapsed = min(self.gravity_elapsed-interval, interval)
            self.game.down()
            self.consume_events()

    def draw_game(self):
        g = self.game
        if not g:
            return
        p = self.palette
        self.backdrop(decorative=False)
        self.text('TETRIS DELUXE', BX, 31, 30, p['primary'], bold=True)
        self.text(MODES[g.mode][0], BX, 67, 16, p['muted'])
        self.soft_rect((BX-7, BY-7, BW+14, BH+14), p['panel'], p['stroke'], radius=11)
        pygame.draw.rect(self.canvas, blend(p['bg'], p['panel'], .55), (BX, BY, BW, BH))
        if self.settings['grid']:
            for i in range(1, COLS):
                pygame.draw.line(self.canvas, p['grid'], (BX+i*CELL, BY), (BX+i*CELL, BY+BH))
            for j in range(1, ROWS):
                pygame.draw.line(self.canvas, p['grid'], (BX, BY+j*CELL), (BX+BW, BY+j*CELL))
        anim = max(0, min(1, self.clear_elapsed / ANIMATION_DURATION))
        for iy, row in enumerate(g.board):
            for ix, color in enumerate(row):
                if color:
                    alpha = int(255 * (1 - anim)**1.6) if iy in g.pending_rows else 255
                    self.draw_block(BX + ix*CELL, BY + iy*CELL, CELL, color, alpha=alpha)
        if not g.over and not g.pending_rows:
            if self.settings['ghost']:
                gy = g.ghost_y()
                if gy != g.y:
                    for cx, cy in g.cells:
                        self.draw_block(BX+(g.x+cx)*CELL, BY+(gy+cy)*CELL,
                                        CELL, COLORS[g.current], ghost=True)
            for cx, cy in g.cells:
                self.draw_block(BX + (g.x+cx)*CELL, BY+(g.y+cy)*CELL, CELL, COLORS[g.current])
        self.draw_sidebar()
        self.draw_particles()
        if self.flash > 0:
            surf = pygame.Surface((BW, BH), pygame.SRCALPHA)
            surf.fill((*p['primary'], int(min(.7, self.flash)*110)))
            self.canvas.blit(surf, (BX, BY))

    def side_panel(self, y, height, label):
        p = self.palette
        self.soft_rect((PANEL_X, y, PANEL_W, height), p['panel'], p['stroke'])
        self.text(label, PANEL_X+16, y+11, 15, p['muted'], bold=True)

    def draw_sidebar(self):
        g = self.game
        p = self.palette
        self.side_panel(93, 106, 'SCORE')
        self.text(f'{g.score:,}', PANEL_X+16, 128, 32, p['primary'], bold=True)
