    def action(self, action):
        if self.state != 'playing' or not self.game or self.game.over:
            return
        if action == 'left':
            self.game.move(-1)
        elif action == 'right':
            self.game.move(1)
        elif action == 'rotate':
            self.game.rotate()
        elif action == 'soft_drop':
            self.game.down(soft=True)
        elif action == 'hard_drop':
            self.game.hard_drop()
            self.gravity_elapsed = 0.
        elif action == 'pause' or action == 'back':
            self.pause()
        elif action == 'restart':
            self.start(self.last_mode)
        self.consume_events()

    def to_logical(self, point):
        ww, wh = self.window.get_size()
        ratio = min(ww/W, wh/H)
        sx, sy = int(W*ratio), int(H*ratio)
        left, top = (ww-sx)//2, (wh-sy)//2
        if ratio == 0:
            return (-999, -999)
        return ((point[0]-left)/ratio, (point[1]-top)/ratio)

    def handle_key(self, event):
        key = pygame.key.name(event.key).lower()
        if self.state == 'settings':
            if self.capture_action:
                if key == 'escape' and self.capture_action != 'back':
                    self.capture_action = None
                elif key not in ('unknown key', 'unknown'):
                    rebind_control(self.settings, self.capture_action, key)
                    self.store.save_settings()
                    self.capture_action = None
                    self.sound.play('select', self.settings)
                return
            if key == 'escape':
                self.settings_back()
            elif key in ('tab', 'page down'):
                self.change_tab(SETTINGS_TABS[(SETTINGS_TABS.index(self.tab)+1) % len(SETTINGS_TABS)])
            elif key == 'page up':
                self.change_tab(SETTINGS_TABS[(SETTINGS_TABS.index(self.tab)-1) % len(SETTINGS_TABS)])
            elif key in ('up', 'down'):
                count = len(CONTROL_LABELS) if self.tab == 'CONTROLS' else len(SETTINGS_ROWS[self.tab])
                self.settings_selected = (self.settings_selected + (1 if key == 'down' else -1)) % count
            elif key in ('left', 'right', 'return', 'space'):
                if self.tab == 'CONTROLS':
                    if key in ('return', 'space'):
                        self.capture(CONTROL_LABELS[self.settings_selected][0])
                else:
                    name = SETTINGS_ROWS[self.tab][self.settings_selected][1]
                    self.apply_setting(name, -1 if key == 'left' else 1)
            return
        if self.state == 'menu':
            options = (self.select_mode, self.open_settings, self.open_stats, self.open_achievements, self.quit)
            if key in ('up', 'down'):
                self.menu_selected = (self.menu_selected + (1 if key == 'down' else -1)) % len(options)
                self.sound.play('select', self.settings)
            elif key in ('return', 'space'):
                options[self.menu_selected]()
            elif key == 'escape':
                self.quit()
            return
        if self.state == 'modes':
            if key == 'escape':
                self.go('menu')
            elif key in ('up', 'down'):
                self.mode_selected = (self.mode_selected + (1 if key == 'down' else -1)) % len(MODES)
                self.sound.play('select', self.settings)
            elif key in ('return', 'space'):
                self.start(list(MODES)[self.mode_selected])
            return
        if self.state in ('stats', 'achievements'):
            if key == 'escape': self.go('menu')
            return
        if self.state == 'result':
            if key == 'escape': self.go('menu')
            elif key == 'return': self.start(self.last_mode)
            return
        if self.state == 'paused':
            options = (lambda: self.go('playing'), self.open_settings,
                       lambda: self.start(self.last_mode), self.abandon)
            if key in (self.settings['controls']['pause'], self.settings['controls']['back'], 'escape'):
                self.go('playing')
            elif key in ('up', 'down'):
                self.pause_selected = (self.pause_selected + (1 if key == 'down' else -1)) % len(options)
                self.sound.play('select', self.settings)
            elif key == 'return':
                options[self.pause_selected]()
            return
        if self.state == 'playing':
            for action, assigned in self.settings['controls'].items():
                if key == assigned:
                    self.action(action)
                    if action in ('left', 'right', 'soft_drop') and self.state == 'playing':
                        self.held[action] = 0.
                        self.repeat_elapsed[action] = 0.
                    return
            if key == 'escape':
                self.pause()

    def select_mode(self):
        self.mode_selected = 0
        self.go('modes')

    def open_stats(self):
        self.go('stats')

    def open_achievements(self):
        self.go('achievements')

    def quit(self):
        if self.game and self.state in ('playing', 'paused', 'settings'):
            self.abandon()
        self.store.save_settings()
        self.running = False

    def handle_events(self):
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                self.quit()
            elif event.type == pygame.VIDEORESIZE and not self.fullscreen:
                self.windowed_size = (max(500, event.w), max(550, event.h))
                self.window = pygame.display.set_mode(self.windowed_size, pygame.RESIZABLE)
            elif event.type == pygame.MOUSEMOTION:
                self.mouse_logical = self.to_logical(event.pos)
            elif event.type == pygame.MOUSEBUTTONDOWN and event.button == 1:
                self.mouse_logical = self.to_logical(event.pos)
                for rect, callback in self.buttons:
                    if rect.collidepoint(self.mouse_logical):
                        callback()
                        break
            elif event.type == pygame.KEYDOWN:
                self.handle_key(event)
            elif event.type == pygame.KEYUP:
                key = pygame.key.name(event.key).lower()
                for action in tuple(self.held):
                    if self.settings['controls'][action] == key:
                        self.held.pop(action, None)
                        self.repeat_elapsed.pop(action, None)

    def render(self):
        self.buttons.clear()
        if self.state == 'menu':
            self.draw_menu()
        elif self.state == 'modes':
            self.draw_modes()
        elif self.state == 'settings':
            self.draw_settings()
        elif self.state == 'stats':
            self.draw_stats()
        elif self.state == 'achievements':
            self.draw_achievements()
        elif self.state == 'playing':
            self.draw_game()
        elif self.state == 'paused':
            self.draw_pause()
        elif self.state == 'result':
            self.draw_result()
        ww, wh = self.window.get_size()
        scale = min(ww/W, wh/H)
        sw, sh = max(1, int(W*scale)), max(1, int(H*scale))
        if sw == W and sh == H:
            image = self.canvas
        else:
            image = pygame.transform.smoothscale(self.canvas, (sw, sh))
        self.window.fill(self.palette['bg'])
        self.window.blit(image, ((ww-sw)//2, (wh-sh)//2))
        pygame.display.flip()

    def run(self):
        try:
            while self.running:
                dt = min(.06, self.clock.tick(FPS) / 1000)
                self.elapsed_ui += dt
                self.handle_events()
                if self.state == 'playing':
                    self.update_game(dt)
                self.update_particles(dt)
                self.sound.update(self.settings, self.state in ('menu','modes','playing','paused','stats','achievements','settings','result'))
                self.render()
        finally:
            if self.game and self.state == 'playing':
                self.abandon()
            self.store.save_settings()
            pygame.quit()


