"""Tetris Deluxe - desktop Pygame edition.

Run: python tetris.py
All artwork, particle effects, and audio are generated by the program.
"""
from __future__ import annotations

import math
import random
import sys
from dataclasses import dataclass

try:
    import pygame
except ImportError:
    print('Tetris Deluxe needs pygame. Install it with: python -m pip install -r requirements.txt')
    raise SystemExit(1)

from tetris_core import (ACHIEVEMENTS, COLS, ROWS, COLORS, MODES, SHAPES,
                         Game, Store, gravity_interval)
from tetris_audio import SoundManager
from tetris_ui_logic import adjust_setting, rebind_control, format_time

W, H = 720, 760
CELL = 25
BX, BY = 76, 92
BW, BH = COLS * CELL, ROWS * CELL
PANEL_X, PANEL_W = 410, 244
FPS = 60
ANIMATION_DURATION = .30

PALETTES = {
    'Neon': {
        'bg': (9, 12, 25), 'panel': (18, 24, 42), 'panel2': (26, 34, 55),
        'primary': (76, 223, 240), 'second': (185, 111, 243),
        'text': (236, 244, 255), 'muted': (139, 159, 182),
        'stroke': (46, 68, 94), 'grid': (32, 46, 65),
    },
    'Classic': {
        'bg': (19, 24, 40), 'panel': (32, 40, 62), 'panel2': (43, 52, 75),
        'primary': (255, 211, 100), 'second': (244, 140, 99),
        'text': (255, 246, 231), 'muted': (175, 184, 199),
        'stroke': (72, 83, 112), 'grid': (51, 62, 84),
    },
    'Minimal': {
        'bg': (20, 22, 24), 'panel': (31, 34, 37), 'panel2': (41, 45, 49),
        'primary': (215, 233, 227), 'second': (128, 169, 154),
        'text': (232, 232, 232), 'muted': (152, 160, 161),
        'stroke': (68, 72, 74), 'grid': (45, 49, 50),
    },
}
SETTINGS_TABS = ('VISUAL', 'GAMEPLAY', 'AUDIO', 'CONTROLS')
SETTINGS_ROWS = {
    'VISUAL': [('Theme', 'theme'), ('Grid lines', 'grid'),
               ('Ghost piece', 'ghost'), ('Particles & glow', 'effects'),
               ('Fullscreen', 'fullscreen')],
    'GAMEPLAY': [('Difficulty', 'difficulty'), ('Game speed', 'speed')],
    'AUDIO': [('Music volume', 'music_volume'), ('Effects volume', 'sfx_volume')],
}
CONTROL_LABELS = [('left', 'MOVE LEFT'), ('right', 'MOVE RIGHT'),
                  ('rotate', 'ROTATE'), ('soft_drop', 'SOFT DROP'),
                  ('hard_drop', 'HARD DROP'), ('pause', 'PAUSE'),
                  ('back', 'BACK / MENU'), ('restart', 'RESTART')]


def blend(a, b, t):
    return tuple(int(x + (y - x) * t) for x, y in zip(a[:3], b[:3]))


def fit_key(name):
    return {'left': 'LEFT', 'right': 'RIGHT', 'up': 'UP', 'down': 'DOWN',
            'space': 'SPACE', 'escape': 'ESC', 'return': 'ENTER'}.get(name, name.upper())


@dataclass
class Particle:
    x: float
    y: float
    vx: float
    vy: float
    life: float
    maximum: float
    radius: float
    color: tuple


class DeluxeApp:
    def __init__(self):
        pygame.init()
        pygame.display.set_caption('Tetris Deluxe')
        self.store = Store()
        self.settings = self.store.settings
        self.window = None
        self.fullscreen = False
        self.windowed_size = (810, 855)
        self.set_fullscreen(self.settings['fullscreen'])
        self.canvas = pygame.Surface((W, H)).convert()
        self.clock = pygame.time.Clock()
        self.fonts = {}
        self.sound = SoundManager()
        self.state = 'menu'
        self.settings_return = 'menu'
        self.tab = SETTINGS_TABS[0]
        self.menu_selected = 0
        self.mode_selected = 0
        self.settings_selected = 0
        self.pause_selected = 0
        self.capture_action = None
        self.buttons = []
        self.game = None
        self.latest_awards = []
        self.last_mode = 'CLASSIC'
        self.gravity_elapsed = 0.
        self.clear_elapsed = 0.
        self.held = {}
        self.repeat_elapsed = {}
        self.particles = []
        self.flash = 0.
        self.elapsed_ui = 0.
        self.running = True
        self.mouse_logical = (-999, -999)
        self.stars = [(random.randrange(W), random.randrange(H), random.randrange(2, 5),
                       random.uniform(.3, 1.8)) for _ in range(42)]
        self.falling_shapes = [(random.randrange(-10, W), random.randrange(-H, H),
                                random.choice(list(SHAPES)), random.uniform(6, 21),
                                random.uniform(.15, .6)) for _ in range(16)]

    def set_fullscreen(self, enabled):
        if enabled:
            try:
                self.window = pygame.display.set_mode((0, 0), pygame.FULLSCREEN)
                self.fullscreen = True
                return
            except pygame.error:
                enabled = False
        self.window = pygame.display.set_mode(self.windowed_size, pygame.RESIZABLE)
        self.fullscreen = False
        self.settings['fullscreen'] = False

    def font(self, size, bold=False):
        key = (size, bold)
        if key not in self.fonts:
            self.fonts[key] = pygame.font.SysFont('consolas', size, bold=bold)
        return self.fonts[key]

    def text(self, content, x, y, size=22, color=None, center=False, bold=False, align='left'):
        color = color if color is not None else self.palette['text']
        rendered = self.font(size, bold).render(str(content), True, color)
        rect = rendered.get_rect()
        if center:
            rect.center = (x, y)
        elif align == 'right':
            rect.topright = (x, y)
        else:
            rect.topleft = (x, y)
        self.canvas.blit(rendered, rect)
        return rect

    @property
    def palette(self):
        return PALETTES[self.settings['theme']]

    def soft_rect(self, rect, fill=None, border=None, radius=15, width=1):
        if fill is not None:
            pygame.draw.rect(self.canvas, fill, rect, border_radius=radius)
        if border is not None:
            pygame.draw.rect(self.canvas, border, rect, width, border_radius=radius)

    def button(self, rect, label, callback, *, highlight=False, font=20, subtle=False):
        rect = pygame.Rect(rect)
        hovered = rect.collidepoint(self.mouse_logical)
        p = self.palette
        bright = p['primary'] if highlight else p['second']
        base = p['panel2'] if not highlight else blend(p['panel2'], bright, .20)
        if hovered:
            base = blend(base, bright, .20)
        if subtle:
            base = p['panel'] if not hovered else p['panel2']
        self.soft_rect(rect, base, bright if hovered or highlight else p['stroke'], radius=12)
        self.text(label, rect.centerx, rect.centery, size=font, color=p['text'], center=True, bold=highlight)
        self.buttons.append((rect, callback))

    def backdrop(self, decorative=True):
        p = self.palette
        self.canvas.fill(p['bg'])
        for yy in range(0, H, 4):
            color = blend(p['bg'], p['panel'], yy / H * .38)
            pygame.draw.rect(self.canvas, color, (0, yy, W, 4))
        if not decorative:
            return
        for sx, sy, radius, rate in self.stars:
            alpha = .35 + .4 * math.sin(self.elapsed_ui * rate + sx) ** 2
            color = blend(p['bg'], p['primary'], alpha)
            pygame.draw.circle(self.canvas, color, (sx, sy), radius // 2)
        if self.settings['effects']:
            for x, y, shape, speed, phase in self.falling_shapes:
                py = (y + self.elapsed_ui * speed) % (H + 160) - 80
                px = x + math.sin(self.elapsed_ui * phase) * 17
                color = blend(p['bg'], p['second'], .14)
                for cx, cy in SHAPES[shape]:
                    pygame.draw.rect(self.canvas, color,
                                     (int(px + cx * 13), int(py + cy * 13), 12, 12), border_radius=3)

